/**
 * 从广告活动名提取机型代码（如 IP14ProMax）
 * 逻辑：取"-"分隔的首段，首段为SP/SB/SD时取第二段
 */
/**
 * 从广告活动名提取机型代码（如 A17, IP14ProMax）
 * 优先用 portfolioName（广告组合名），回退到 campaignName
 */
// 机型代码归一化：符号/大小写统一，使广告活动名与库存MSKU提取出的code一致（联动关键）
const _mapKeysLower = new Map<string, string>();
for (const _k of Object.keys(CAMPAIGN_MODEL_MAP)) _mapKeysLower.set(_k.toLowerCase(), _k);

function normalizeModelCode(code: string): string {
  if (!code) return '';
  const raw = code.trim().replace(/\s+/g, '');
  // 依次尝试多种归一形态，第一个命中标准库即采用（避免 + → Plus 误伤 REVVL/V+ 等原生带+的key）
  const candidates = [
    raw,
    raw.replace(/\+/g, 'Plus'),
    raw.replace(/\/5G$/i, ''),
    raw.replace(/\+/g, 'Plus').replace(/\/5G$/i, ''),
    raw.replace(/^Fold(\d)/i, 'Z/Fold$1'),
    raw.replace(/\+/g, 'Plus').replace(/^Fold(\d)/i, 'Z/Fold$1'),
  ];
  for (const cand of candidates) {
    const hit = _mapKeysLower.get(cand.toLowerCase());
    if (hit) return hit;
  }
  return raw;
}

export function extractModelCode(campaignName: string, portfolioName?: string): string {
  // 优先从 portfolioName 提取（广告组合名通常更准确地代表机型）
  if (portfolioName) {
    const pfFirstPart = portfolioName.split('-')[0].trim();
    // 跳过无效组合名(如 "No Portfolio" / 未设置 / (not set))，回退到活动名
    if (pfFirstPart && !/^(SP|SB|SD|NO\s*PORTFOLIO|未设置|\(NOT SET\)|N\/A)$/i.test(pfFirstPart)) {
      return normalizeModelCode(pfFirstPart);
    }
  }
  if (!campaignName) return '';
  const firstPart = campaignName.split('-')[0].trim();
  // "SP-A12-xxx" format: firstPart is exactly "SP"/"SB"/"SD"
  if (/^(SP|SB|SD)$/i.test(firstPart) && campaignName.split('-').length > 1) {
    return normalizeModelCode(campaignName.split('-')[1].trim());
  }
  // "SP A12 - xxx" format: firstPart starts with "SP "/"SB "/"SD " (space-separated prefix)
  const spacePrefixMatch = firstPart.match(/^(?:SP|SB|SD)\s+(.+)$/i);
  if (spacePrefixMatch) {
    return normalizeModelCode(spacePrefixMatch[1].trim());
  }
  return normalizeModelCode(firstPart || '');
}

/**
 * 从广告活动名提取机型可读名（如 iPhone 14 Pro Max）
 * 两级查找：extractModelCode → CAMPAIGN_MODEL_MAP → 组名
 */
export function extractModelName(campaignName: string): string {
  const code = extractModelCode(campaignName);
  if (!code) return '未知';
  return CAMPAIGN_MODEL_MAP[code] || CAMPAIGN_MODEL_MAP[code.toLowerCase()] || code;
}


export function resolveModelCode(input: string, portfolioName?: string): string {
  if (!input) return '';
  return extractModelCode(input, portfolioName);
}
